// Generates supabase/seed.sql from src/data/resources.json (the single source of truth for the library).
import { readFileSync, writeFileSync } from 'node:fs'

const { resources, paths } = JSON.parse(readFileSync('src/data/resources.json', 'utf8'))
const q = (s: string | null | undefined) => (s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`)
const arr = (a: string[]) => `array[${a.map(q).join(',')}]::text[]`

const lines = ['-- Generated by scripts/gen-seed.ts. Do not edit by hand.', 'begin;']
resources.forEach((r: Record<string, any>, i: number) => {
  lines.push(
    `insert into public.resources (id,title,url,source,kind,topics,level,minutes,why,position) values (${q(r.id)},${q(r.title)},${q(r.url)},${q(r.source)},${q(r.kind)},${arr(r.topics)},${q(r.level)},${r.minutes ?? 'null'},${q(r.why)},${i}) ` +
      `on conflict (id) do update set title=excluded.title,url=excluded.url,source=excluded.source,kind=excluded.kind,topics=excluded.topics,level=excluded.level,minutes=excluded.minutes,why=excluded.why,position=excluded.position;`,
  )
})
paths.forEach((p: Record<string, any>, i: number) => {
  lines.push(
    `insert into public.learning_paths (id,title,blurb,weeks,steps,position) values (${q(p.id)},${q(p.title)},${q(p.blurb)},${p.weeks},${q(JSON.stringify(p.steps))}::jsonb,${i}) ` +
      `on conflict (id) do update set title=excluded.title,blurb=excluded.blurb,weeks=excluded.weeks,steps=excluded.steps,position=excluded.position;`,
  )
})
lines.push('commit;', '')
writeFileSync('supabase/seed.sql', lines.join('\n'))
console.log(`Wrote supabase/seed.sql (${resources.length} resources, ${paths.length} paths)`)

// Public marketing counts (numbers only, no titles/links, so nothing paid ships in the client bundle).
const topics: Record<string, number> = {}
for (const r of resources) for (const t of r.topics) topics[t] = (topics[t] ?? 0) + 1
writeFileSync('src/data/topicCounts.json', JSON.stringify({ total: resources.length, topics, paths: paths.length }, null, 1) + '\n')
console.log('Wrote src/data/topicCounts.json')
